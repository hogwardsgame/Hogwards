async def cmd_info(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    user_id = update.effective_user.id
    if not user_exists(user_id):
        await update.message.reply_text(t(user_id, "not_registered"))
        return
    text, _ = SECTIONS["main"]
    await update.message.reply_text(text, parse_mode="Markdown",
                                    reply_markup=_main_menu_markup())

async def cb_info(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    query   = update.callback_query
    await query.answer()
    section = query.data.split(":", 1)[1]

    if section not in SECTIONS:
        await query.edit_message_text("❌ Раздел не найден.")
        return

    text, _ = SECTIONS[section]
    if section == "main":
        markup = _main_menu_markup()
    else:
        markup = InlineKeyboardMarkup([_back_btn()])

    await query.edit_message_text(text, parse_mode="Markdown", reply_markup=markup)

def register_info_handlers(app):
    app.add_handler(CommandHandler("info", cmd_info))
    app.add_handler(CallbackQueryHandler(cb_info, pattern=r"^info:"))
